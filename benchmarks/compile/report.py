"""Generate the compiled benchmark documentation page and charts."""

from __future__ import annotations

import json
import warnings
from collections import Counter, defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

AUTOGENERATED_FRONTMATTER = """<!---
WARNING: This file is auto-generated.
Do not edit manually — changes will be overwritten on the next build.
-->

"""


def _format_time(seconds):
    if seconds is None:
        return "—"
    if seconds < 1e-6:
        return f"{seconds * 1e9:.2f} ns"
    if seconds < 1e-3:
        return f"{seconds * 1e6:.2f} us"
    if seconds < 1:
        return f"{seconds * 1e3:.2f} ms"
    return f"{seconds:.3f} s"


def _format_speedup(value):
    if value is None:
        return "—"
    return f"{value:.2f}x"


def _cell(value) -> str:
    return str(value).replace("|", "\\|")


def _table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |"]
    lines.append("|" + "|".join("---" for _ in headers) + "|")
    for row in rows:
        lines.append("| " + " | ".join(_cell(cell) for cell in row) + " |")
    return "\n".join(lines)


def _error_signature(tail: str | None) -> str:
    if not tail:
        return ""
    lines = [line.strip() for line in tail.splitlines() if line.strip()]
    for line in reversed(lines):
        if any(word in line for word in ("Error:", "Unsupported:", "Exception:")):
            return line[:180]
    return lines[-1][:180] if lines else ""


def load_compiled_results(results_dir: Path) -> tuple[dict | None, str | None]:
    """Load the newest available compiled results, preferring the full level."""
    for level in ("full", "reduced"):
        path = results_dir / f"compiled-{level}.json"
        if not path.exists():
            continue
        try:
            return json.loads(path.read_text()), level
        except (OSError, json.JSONDecodeError) as exc:
            warnings.warn(f"Could not read {path}: {exc}", stacklevel=2)
    return None, None


def _build_metadata_section(metadata: dict) -> list[str]:
    protocol = metadata.get("protocol") or {}
    lines = ["## Metadata", ""]
    lines.append(f"- **Level**: {metadata.get('suite_level', 'unknown')}")
    lines.append(f"- **Date**: {metadata.get('date', 'unknown')}")
    lines.append(f"- **PyTorch**: {metadata.get('torch_version', 'unknown')}")
    lines.append(f"- **CUDA**: {metadata.get('cuda_version') or 'N/A'}")
    lines.append(f"- **GPU**: {metadata.get('gpu_name') or 'N/A'}")
    lines.append(f"- **Python**: {metadata.get('python_version', 'unknown')}")
    lines.append(f"- **Commit**: `{metadata.get('commit_sha', 'unknown')}`")
    if protocol:
        lines.append(
            f"- **Timing protocol**: {protocol.get('warmup')} warmup, "
            f"{protocol.get('iters')} measured iterations"
        )
    lines.append("")
    return lines


def _build_compatibility_section(rows: list[dict]) -> list[str]:
    lines = ["## Compatibility Matrix", ""]
    if not rows:
        lines += ["No rows recorded.", ""]
        return lines
    table_rows = []
    for row in sorted(
        rows,
        key=lambda r: (
            r.get("op", ""),
            r.get("level", ""),
            r.get("method", ""),
            r.get("device", ""),
            r.get("config", ""),
        ),
    ):
        breaks = row.get("graph_breaks")
        table_rows.append(
            [
                row.get("op", ""),
                row.get("level", ""),
                row.get("method", ""),
                row.get("device", ""),
                row.get("config", ""),
                row.get("effective_class", row.get("cell_class", "")),
                "—" if breaks is None else breaks,
                f"{row.get('max_rel_diff', 0.0):.3g}"
                if row.get("max_rel_diff") is not None
                else "—",
                _error_signature(row.get("traceback_tail")),
            ]
        )
    lines.append(
        _table(
            [
                "Operator",
                "Level",
                "Method",
                "Device",
                "Config",
                "Class",
                "Graph breaks",
                "Max rel diff",
                "Error",
            ],
            table_rows,
        )
    )
    lines.append("")
    return lines


def _build_break_details_section(rows: list[dict]) -> list[str]:
    lines = ["### Graph-break details", ""]
    break_rows = [
        row
        for row in rows
        if (row.get("graph_breaks") or 0) > 0 or row.get("break_locations")
    ]
    if not break_rows:
        lines += ["No graph breaks were recorded.", ""]
        return lines
    for row in sorted(
        break_rows,
        key=lambda r: (
            r.get("op", ""),
            r.get("method", ""),
            r.get("device", ""),
            r.get("config", ""),
        ),
    ):
        lines.append(
            f"- **{row.get('op', '')}** ({row.get('level', '')}, "
            f"{row.get('method', '')}, {row.get('device', '')}, "
            f"{row.get('config', '')}) — {row.get('graph_breaks')} breaks"
        )
        for location in row.get("break_locations", [])[:3]:
            lines.append(f"  - `{_cell(location)}`")
    lines.append("")
    return lines


def _build_speedup_section(rows: list[dict]) -> list[str]:
    lines = ["## Speedups", ""]
    speed_rows = [
        row
        for row in rows
        if row.get("speedup") is not None and row.get("config") == "default"
    ]
    if not speed_rows:
        lines += ["No timed rows recorded.", ""]
        return lines
    table_rows = []
    for row in sorted(speed_rows, key=lambda r: r["speedup"], reverse=True):
        table_rows.append(
            [
                row.get("op", ""),
                row.get("level", ""),
                row.get("method", ""),
                row.get("device", ""),
                row.get("dtype", ""),
                _format_time(row.get("eager_time")),
                _format_time(row.get("compiled_time")),
                _format_speedup(row.get("speedup")),
                row.get("effective_class", row.get("cell_class", "")),
            ]
        )
    lines.append(
        _table(
            [
                "Operator",
                "Level",
                "Method",
                "Device",
                "Dtype",
                "Eager",
                "Compiled",
                "Speedup",
                "Class",
            ],
            table_rows,
        )
    )
    lines.append("")
    return lines


def _has_speedup_chart(rows: list[dict], device: str) -> bool:
    return any(
        row.get("device") == device
        and row.get("config") == "default"
        and row.get("level") == "wrapper"
        and row.get("speedup") is not None
        for row in rows
    )


def _has_wrapper_vs_inner_chart(rows: list[dict], device: str) -> bool:
    grouped: dict[tuple[str, str, str], set[str]] = defaultdict(set)
    for row in rows:
        if (
            row.get("device") == device
            and row.get("config") == "default"
            and row.get("speedup") is not None
        ):
            key = (
                row.get("op", ""),
                row.get("method", ""),
                row.get("dtype", ""),
            )
            grouped[key].add(row.get("level", ""))
    return any({"wrapper", "inner"} <= levels for levels in grouped.values())


def _chart_links(
    rows: list[dict],
    *,
    speedup: bool = False,
    wrapper_inner: bool = False,
    pipeline: bool = False,
    pipeline_rows: list[dict] | None = None,
    prefix: str = "../assets",
) -> list[str]:
    sections: list[str] = []
    for device, label in (("cpu", "CPU"), ("cuda", "GPU")):
        charts: list[str] = []
        if speedup and _has_speedup_chart(rows, device):
            charts.append(
                f"![Compiled speedup — {label}]({prefix}/speedup_{device}.png)"
            )
        if wrapper_inner and _has_wrapper_vs_inner_chart(rows, device):
            charts.append(
                "![Wrapper vs inner compile unit — "
                f"{label}]({prefix}/speedup_wrapper_vs_inner_{device}.png)"
            )
        if charts:
            sections += [f"### {label}", ""]
            for chart in charts:
                sections += [chart, ""]
    if pipeline and any(
        row.get("speedup") is not None for row in (pipeline_rows or [])
    ):
        sections += [
            f"![Pipeline speedups]({prefix}/pipeline_speedups.png)",
            "",
        ]
    if not sections:
        return []
    return ["## Charts", "", *sections]


def _build_summary_section(rows: list[dict]) -> list[str]:
    lines = ["## Summary", ""]
    if not rows:
        lines += ["No rows recorded.", ""]
        return lines

    class_counts = Counter(
        row.get("effective_class", row.get("cell_class", "unknown")) for row in rows
    )
    lines += ["### Effective classes", ""]
    lines.append(
        _table(
            ["Class", "Rows"],
            [[name, count] for name, count in sorted(class_counts.items())],
        )
    )
    lines.append("")

    device_counts = Counter(row.get("device", "unknown") for row in rows)
    lines += ["### Rows by device", ""]
    lines.append(
        _table(
            ["Device", "Rows"],
            [[name, count] for name, count in sorted(device_counts.items())],
        )
    )
    lines.append("")

    failures = [
        row
        for row in rows
        if row.get("effective_class") in {"fails_loud", "fails_silent"}
    ]
    if failures:
        lines += ["### Failure signatures", ""]
        lines.append(
            _table(
                ["Operator", "Method", "Device", "Config", "Signature"],
                [
                    [
                        row.get("op", ""),
                        row.get("method", ""),
                        row.get("device", ""),
                        row.get("config", ""),
                        _error_signature(row.get("traceback_tail")),
                    ]
                    for row in failures
                ],
            )
        )
        lines.append("")
    return lines


def _build_functional_section(rows: list[dict]) -> list[str]:
    lines = ["## Functional Kernels", ""]
    functional = [row for row in rows if row.get("category") == "functional"]
    if not functional:
        lines += ["No functional-kernel rows recorded.", ""]
        return lines
    lines.append(
        _table(
            [
                "Operator",
                "Device",
                "Dtype",
                "Config",
                "Class",
                "Graph breaks",
                "Speedup",
            ],
            [
                [
                    row.get("op", ""),
                    row.get("device", ""),
                    row.get("dtype", ""),
                    row.get("config", ""),
                    row.get("effective_class", row.get("cell_class", "")),
                    "—" if row.get("graph_breaks") is None else row.get("graph_breaks"),
                    _format_speedup(row.get("speedup")),
                ]
                for row in sorted(
                    functional,
                    key=lambda r: (
                        r.get("op", ""),
                        r.get("device", ""),
                        r.get("dtype", ""),
                        r.get("config", ""),
                    ),
                )
            ],
        )
    )
    lines.append("")
    return lines


def _build_phase_section(name: str, phase_rows: list[dict]) -> list[str]:
    lines = [f"## {name}", ""]
    if not phase_rows:
        lines += ["These sections require the full suite.", ""]
        return lines

    if name == "Recompilation":
        headers = ["Operator", "Level", "Device", "Recompiles", "Agrees after", "Notes"]
        rows = [
            [
                row.get("op", ""),
                row.get("level", ""),
                row.get("device", ""),
                row.get("recompiles"),
                row.get("agrees_after"),
                (row.get("notes") or "")[:120],
            ]
            for row in phase_rows
        ]
    elif name == "Autograd":
        headers = ["Operator", "Level", "Class", "Max rel diff", "Notes"]
        rows = [
            [
                row.get("op", ""),
                row.get("level", ""),
                row.get("cell_class", ""),
                row.get("max_rel_diff"),
                (row.get("notes") or "")[:120],
            ]
            for row in phase_rows
        ]
    else:
        headers = ["Pipeline", "Level", "Config", "Class", "Speedup", "Breaks", "Notes"]
        rows = [
            [
                row.get("op", ""),
                row.get("level", ""),
                row.get("config", ""),
                row.get("cell_class", ""),
                _format_speedup(row.get("speedup")),
                row.get("graph_breaks"),
                (row.get("notes") or "")[:120],
            ]
            for row in phase_rows
        ]
    lines.append(_table(headers, rows))
    lines.append("")
    return lines


def _build_dtype_section(rows: list[dict]) -> list[str]:
    lines = ["## Performance by dtype", ""]
    dtypes = sorted(
        {
            row.get("dtype", "")
            for row in rows
            if row.get("config") == "default" and row.get("speedup") is not None
        }
    )
    for dtype in dtypes:
        subset = [
            row
            for row in rows
            if row.get("dtype") == dtype
            and row.get("config") == "default"
            and row.get("speedup") is not None
        ]
        lines += [f"### {dtype}", ""]
        lines.append(
            _table(
                ["Operator", "Level", "Method", "Device", "Speedup", "Class"],
                [
                    [
                        row.get("op", ""),
                        row.get("level", ""),
                        row.get("method", ""),
                        row.get("device", ""),
                        _format_speedup(row.get("speedup")),
                        row.get("effective_class", row.get("cell_class", "")),
                    ]
                    for row in sorted(
                        subset, key=lambda r: r.get("speedup") or 0, reverse=True
                    )
                ],
            )
        )
        lines.append("")
    if not lines[2:]:
        lines += ["No timed rows recorded.", ""]
    return lines


def _build_wrapper_inner_section(rows: list[dict]) -> list[str]:
    from statistics import median

    lines = ["## Wrapper vs inner by operator", ""]
    grouped: dict[tuple[str, str, str], list[float]] = defaultdict(list)
    for row in rows:
        if row.get("config") == "default" and row.get("speedup") is not None:
            grouped[
                (row.get("op", ""), row.get("device", ""), row.get("level", ""))
            ].append(row["speedup"])

    table_rows = []
    keys = sorted({(op, device) for op, device, _level in grouped})
    for op, device in keys:
        wrapper = grouped.get((op, device, "wrapper"))
        inner = grouped.get((op, device, "inner"))
        table_rows.append(
            [
                op,
                device,
                _format_speedup(median(wrapper)) if wrapper else "—",
                _format_speedup(median(inner)) if inner else "—",
            ]
        )
    if table_rows:
        lines.append(
            _table(
                ["Operator", "Device", "Wrapper median", "Inner median"],
                table_rows,
            )
        )
        lines.append("")
    else:
        lines += ["No timed rows recorded.", ""]
    return lines


def _build_chain_section(rows: list[dict]) -> list[str]:
    chain_ops = {"Chain", "Add", "Sampling"}
    return _build_speedup_section([row for row in rows if row.get("op") in chain_ops])


def _page(title: str, intro: str, sections: list[list[str]]) -> str:
    lines = [f"# {title}", "", intro, ""]
    for section in sections:
        lines.extend(section)
    lines += [
        "---",
        "",
        (
            "See [Methodology](methodology.md) for timing, graph-break, and "
            "level definitions."
        ),
        "",
    ]
    return AUTOGENERATED_FRONTMATTER + "\n".join(lines)


def _no_data_page(title: str) -> str:
    return (
        AUTOGENERATED_FRONTMATTER
        + f"# {title}\n\n"
        + "No compiled benchmark data available. Run `just bench` for the "
        + "reduced suite or `just bench-compiled` for the full suite.\n"
    )


def build_compiled_pages(data: dict | None, level: str | None) -> dict[str, str]:
    """Build every compiled docs page keyed by filename."""
    filenames = [
        "index.md",
        "float-vs-complex.md",
        "wrapper-vs-inner.md",
        "autograd.md",
        "chains.md",
    ]
    if data is None or level is None:
        return {name: _no_data_page("Compiled Benchmarks") for name in filenames}

    metadata = data.get("metadata", {})
    rows = data.get("rows", [])
    phases = data.get("phases", {})

    index_sections = [
        _build_metadata_section(metadata),
        _build_compatibility_section(rows),
        _build_break_details_section(rows),
        _build_summary_section(rows),
        _build_phase_section("Recompilation", phases.get("recompile", [])),
        [
            "## Sections",
            "",
            "- [Float vs Complex Performance](float-vs-complex.md)",
            "- [Wrapper vs Inner Performance](wrapper-vs-inner.md)",
            "- [Autograd Performance](autograd.md)",
            "- [Chain Performance](chains.md)",
            "",
        ],
    ]
    if level != "full":
        index_sections.append(
            [
                "## Full-only Phases",
                "",
                (
                    "Autograd and pipeline checks require the full suite; "
                    "this page was generated from a reduced run."
                ),
                "",
            ]
        )
    else:
        index_sections.append(
            [
                "## Phase Coverage",
                "",
                (
                    "Phase coverage is CUDA-only, recompilation is "
                    "forward-only, autograd is deep-dive-only, and each phase "
                    "uses the case's first dtype."
                ),
                "",
            ]
        )

    pages = {
        "index.md": _page(
            "Compiled Benchmarks",
            "Eager vs `torch.compile` performance and compatibility. Graph-break "
            "counts come from `torch._dynamo.explain` and are PyTorch-version "
            "dependent.",
            index_sections,
        ),
        "float-vs-complex.md": _page(
            "Float vs Complex Performance",
            "Compiled speedups split by dtype. Complex-native operators use "
            "complex64; the rest use their natural real dtype.",
            [
                _build_dtype_section(rows),
                _chart_links(rows, speedup=True),
            ],
        ),
        "wrapper-vs-inner.md": _page(
            "Wrapper vs Inner Performance",
            "The wrapper level compiles the `NamedLinop` call path, including "
            "shape checks and context bookkeeping. The inner level compiles the "
            "bare `fn`/`adj_fn`/`normal_fn`.",
            [
                _build_wrapper_inner_section(rows),
                _build_break_details_section(rows),
                _build_functional_section(rows),
                _chart_links(rows, wrapper_inner=True),
            ],
        ),
        "autograd.md": _page(
            "Autograd Performance",
            "Compiled backward checks from the full suite. Reduced runs do not "
            "collect autograd results.",
            [
                _build_phase_section("Autograd", phases.get("autograd", [])),
            ],
        ),
        "chains.md": _page(
            "Chain Performance",
            "Performance of composed operators and the full-suite fixed-point "
            "pipeline checks.",
            [
                _build_chain_section(rows),
                _build_phase_section("Pipeline", phases.get("pipeline", [])),
                _chart_links(
                    rows,
                    pipeline=True,
                    pipeline_rows=phases.get("pipeline", []),
                ),
            ],
        ),
    }
    return pages


def build_compiled_markdown(data: dict | None, level: str | None) -> str:
    """Compatibility helper returning the compiled index page."""
    return build_compiled_pages(data, level)["index.md"]


def _plot_speedup_bars(rows: list[dict], device: str, assets_dir: Path) -> None:
    selected = [
        row
        for row in rows
        if row.get("device") == device
        and row.get("config") == "default"
        and row.get("level") == "wrapper"
        and row.get("speedup") is not None
    ]
    if not selected:
        return

    selected.sort(key=lambda row: row["speedup"])
    labels = [
        f"{row['op']} ({row['method']}, {row.get('dtype', '')})" for row in selected
    ]
    values = [row["speedup"] for row in selected]
    colors = ["#2E7D32" if value >= 1.0 else "#C62828" for value in values]

    fig, ax = plt.subplots(figsize=(10, max(4, len(selected) * 0.35)))
    ax.barh(labels, values, color=colors)
    ax.axvline(1.0, color="black", linewidth=0.8, linestyle="--")
    ax.set_xlabel("Compiled speedup (eager / compiled)")
    ax.set_title(f"Compiled speedup — {device.upper()} (default config)")
    ax.grid(True, axis="x", ls="--", alpha=0.5)
    fig.tight_layout()
    assets_dir.mkdir(parents=True, exist_ok=True)
    fig.savefig(assets_dir / f"speedup_{device}.png", dpi=150)
    plt.close(fig)


def _plot_wrapper_vs_inner(rows: list[dict], device: str, assets_dir: Path) -> None:
    grouped: dict[tuple[str, str, str], dict[str, float]] = defaultdict(dict)
    for row in rows:
        if (
            row.get("device") == device
            and row.get("config") == "default"
            and row.get("speedup") is not None
        ):
            key = (
                row.get("op", ""),
                row.get("method", ""),
                row.get("dtype", ""),
            )
            grouped[key][row.get("level", "")] = row["speedup"]

    selected = {
        key: levels
        for key, levels in grouped.items()
        if "wrapper" in levels and "inner" in levels
    }
    if not selected:
        return

    keys = sorted(selected)
    x = np.arange(len(keys))
    width = 0.38
    fig, ax = plt.subplots(figsize=(10, max(4, len(keys) * 0.6)))
    ax.bar(
        x - width / 2,
        [selected[key]["wrapper"] for key in keys],
        width,
        label="wrapper",
        color="#4C72B0",
    )
    ax.bar(
        x + width / 2,
        [selected[key]["inner"] for key in keys],
        width,
        label="inner",
        color="#7FB3D5",
    )
    ax.axhline(1.0, color="black", linewidth=0.8, linestyle="--")
    ax.set_xticks(x)
    ax.set_xticklabels(
        [f"{op} ({method}, {dtype})" for op, method, dtype in keys],
        rotation=45,
        ha="right",
        fontsize=8,
    )
    ax.set_ylabel("Compiled speedup (eager / compiled)")
    ax.set_title(f"Wrapper vs inner compile unit — {device.upper()}")
    ax.legend()
    ax.grid(True, axis="y", ls="--", alpha=0.5)
    fig.tight_layout()
    assets_dir.mkdir(parents=True, exist_ok=True)
    fig.savefig(assets_dir / f"speedup_wrapper_vs_inner_{device}.png", dpi=150)
    plt.close(fig)


def _plot_pipeline_speedups(data: dict, assets_dir: Path) -> None:
    rows = [
        row
        for row in data.get("phases", {}).get("pipeline", [])
        if row.get("speedup") is not None
    ]
    if not rows:
        return
    labels = [
        f"{row.get('op', '')} ({row.get('level', '')}, {row.get('config', '')})"
        for row in rows
    ]
    values = [row["speedup"] for row in rows]
    colors = ["#2E7D32" if value >= 1.0 else "#C62828" for value in values]
    fig, ax = plt.subplots(figsize=(10, max(4, len(rows) * 0.5)))
    ax.barh(labels, values, color=colors)
    ax.axvline(1.0, color="black", linewidth=0.8, linestyle="--")
    ax.set_xlabel("Compiled speedup (eager / compiled)")
    ax.set_title("Pipeline speedups")
    ax.grid(True, axis="x", ls="--", alpha=0.5)
    fig.tight_layout()
    assets_dir.mkdir(parents=True, exist_ok=True)
    fig.savefig(assets_dir / "pipeline_speedups.png", dpi=150)
    plt.close(fig)


def plot_compiled_charts(data: dict, level: str, assets_dir: Path) -> None:
    rows = data.get("rows", [])
    for device in ("cpu", "cuda"):
        _plot_speedup_bars(rows, device, assets_dir)
        _plot_wrapper_vs_inner(rows, device, assets_dir)
    _plot_pipeline_speedups(data, assets_dir)


def render_compiled_report(results_dir: Path, docs_dir: Path, assets_dir: Path) -> None:
    data, level = load_compiled_results(results_dir)
    docs_dir.mkdir(parents=True, exist_ok=True)
    pages = build_compiled_pages(data, level)
    for filename, content in pages.items():
        (docs_dir / filename).write_text(content)
    if data is not None:
        plot_compiled_charts(data, level or "", assets_dir)
    print(f"Compiled benchmark report generated at {docs_dir}")
